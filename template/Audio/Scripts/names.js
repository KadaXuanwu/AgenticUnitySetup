/* __GAME__: after every bank build, from FMOD Studio or fmodstudiocl, write the project's events, snapshots,
   buses, VCAs and parameters as C# names into Unity/Assets/__GAME__/Runtime/Audio/Fmod.cs. Code never spells a
   path, and renaming or deleting an event the game plays fails to compile instead of failing silent. */

(function () {
    var OUTPUT = "/../../Unity/Assets/__GAME__/Runtime/Audio/Fmod.cs";

    function identifier(name) {
        var words = name.replace(/[^A-Za-z0-9]+/g, " ").trim().split(" ");
        var id = words.map(function (w) { return w.charAt(0).toUpperCase() + w.slice(1); }).join("");
        return /^[0-9]/.test(id) ? "_" + id : id || "_";
    }

    function byName(a, b) { return a.name < b.name ? -1 : a.name > b.name ? 1 : 0; }

    function eventLines(folder, indent, out) {
        var items = folder.items.slice().sort(byName);
        items.forEach(function (item) {
            if (item.isOfType("EventFolder")) {
                // Read-only names: nothing to reset on entering play mode.
                out.push(indent + "[NoAutoStaticsCleanup]");
                out.push(indent + "public static class " + identifier(item.name) + " {");
                eventLines(item, indent + "    ", out);
                out.push(indent + "}");
            } else if (item.isOfExactType("Event")) {
                out.push(indent + "public static readonly EventReference " + identifier(item.name) +
                    " = Ref(\"" + item.id + "\", \"" + item.getPath() + "\");");
            }
        });
    }

    function constants(title, objects, value, out) {
        out.push("        public static class " + title + " {");
        objects.slice().sort(byName).forEach(function (o) {
            out.push("            public const string " + identifier(o.name) + " = \"" + value(o) + "\";");
        });
        out.push("        }");
        out.push("");
    }

    function generate() {
        var p = studio.project;
        var model = p.model;
        var out = [
            "// Generated by Audio/__GAME__/Scripts/names.js on every FMOD bank build. Do not edit.",
            "using FMODUnity;",
            "using Unity.Scripting.LifecycleManagement;",
            "",
            "namespace __GAME__.Runtime.Audio {",
            "    public static class Fmod {",
            "        public static class Events {"
        ];
        eventLines(p.workspace.masterEventFolder, "            ", out);
        out.push("        }");
        out.push("");
        out.push("        [NoAutoStaticsCleanup]");
        out.push("        public static class Snapshots {");
        model.Snapshot.findInstances().sort(byName).forEach(function (s) {
            out.push("            public static readonly EventReference " + identifier(s.name) +
                " = Ref(\"" + s.id + "\", \"" + s.getPath() + "\");");
        });
        out.push("        }");
        out.push("");
        var buses = model.MixerGroup.findInstances().concat(model.MixerReturn.findInstances());
        buses = buses.filter(function (b) { return b.getPath().indexOf("bus:/") === 0; });
        out.push("        public static class Buses {");
        out.push("            public const string Master = \"bus:/\";");
        buses.slice().sort(function (a, b) { return a.getPath() < b.getPath() ? -1 : 1; }).forEach(function (b) {
            out.push("            public const string " + identifier(b.getPath().substring(5)) + " = \"" + b.getPath() + "\";");
        });
        out.push("        }");
        out.push("");
        constants("Vcas", model.MixerVCA.findInstances(), function (v) { return v.getPath(); }, out);
        constants("Parameters", model.ParameterPreset.findInstances(), function (pr) { return pr.name; }, out);
        out.push("        private static EventReference Ref(string guid, string path) {");
        out.push("            EventReference reference = new EventReference { Guid = FMOD.GUID.Parse(guid) };");
        out.push("#if UNITY_EDITOR");
        out.push("            reference.Path = path;");
        out.push("#endif");
        out.push("            return reference;");
        out.push("        }");
        out.push("    }");
        out.push("}");
        var text = out.join("\n") + "\n";

        var path = p.filePath.substr(0, p.filePath.lastIndexOf("/")) + OUTPUT;
        var file = studio.system.getFile(path);
        if (file.exists() && file.open(studio.system.openMode.ReadOnly)) {
            var old = file.readText(1 << 20);
            file.close();
            if (old === text) {
                return;
            }
        }
        if (!file.open(studio.system.openMode.WriteOnly)) {
            console.error("__GAME__: cannot write " + path);
            return;
        }
        file.writeText(text);
        file.close();
        console.log("__GAME__: wrote " + path);
    }

    studio.project.buildEndedConnect(function (success) {
        if (success) {
            generate();
        }
    });
})();
